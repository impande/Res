// Serves shared portfolio HTML from Firestore via REST API.
// Writes are done client-side via Firebase SDK; this function only handles GET (serving).
const FS_BASE = 'https://firestore.googleapis.com/v1/projects/resume-ai-2eda1/databases/(default)/documents/portfolios';
const FS_KEY  = 'AIzaSyDUgpJQ8PbQgwqj1EUAe9Va4iG8BnNQm10';

const CORS = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'Content-Type',
  'Access-Control-Allow-Methods': 'GET, OPTIONS',
};

exports.handler = async function(event) {
  if (event.httpMethod === 'OPTIONS') return { statusCode: 204, headers: CORS, body: '' };

  // ── GET: serve stored portfolio HTML (via /p/:slug redirect) ─────────────
  if (event.httpMethod === 'GET') {
    const id = (event.queryStringParameters || {}).id;
    if (!id) {
      return { statusCode: 404, headers: { 'Content-Type': 'text/html; charset=utf-8' }, body: notFound() };
    }
    try {
      const fsResp = await fetch(`${FS_BASE}/${encodeURIComponent(id)}?key=${FS_KEY}`);
      if (fsResp.status === 404) {
        return { statusCode: 404, headers: { 'Content-Type': 'text/html; charset=utf-8', 'Cache-Control': 'no-store' }, body: notFound() };
      }
      if (!fsResp.ok) {
        const err = await fsResp.json().catch(() => ({}));
        if (err.error && (err.error.status === 'NOT_FOUND' || err.error.status === 'PERMISSION_DENIED')) {
          return { statusCode: 404, headers: { 'Content-Type': 'text/html; charset=utf-8', 'Cache-Control': 'no-store' }, body: notFound() };
        }
        throw new Error('Firestore read ' + fsResp.status + ': ' + JSON.stringify(err));
      }
      const doc = await fsResp.json();
      const html = doc.fields && doc.fields.html && doc.fields.html.stringValue;
      if (!html) {
        return { statusCode: 404, headers: { 'Content-Type': 'text/html; charset=utf-8', 'Cache-Control': 'no-store' }, body: notFound() };
      }
      // ── Analytics: increment the view counter (best-effort, awaited so it lands
      //    on Lambda). Racy under heavy concurrency, which is fine for a counter. ──
      try {
        const cur = parseInt((doc.fields.views && doc.fields.views.integerValue) || '0', 10) || 0;
        await fetch(`${FS_BASE}/${encodeURIComponent(id)}?key=${FS_KEY}&updateMask.fieldPaths=views`, {
          method: 'PATCH',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ fields: { views: { integerValue: String(cur + 1) } } }),
        });
      } catch (e) { /* never block serving on the counter */ }
      return {
        statusCode: 200,
        headers: { 'Content-Type': 'text/html; charset=utf-8', 'Cache-Control': 'no-store' },
        body: withLiveTestimonials(html),
      };
    } catch (e) {
      return {
        statusCode: 500,
        headers: { 'Content-Type': 'text/html' },
        body: '<h1>Error</h1><pre>' + e.message + '</pre>',
      };
    }
  }

  return { statusCode: 405, headers: CORS, body: 'Method not allowed' };
};

// Ensures every served portfolio page renders its APPROVED visitor testimonials
// live from Firestore — including pages published before that script existed.
// Pages generated by the current builder already carry this logic (they contain
// a documents:runQuery call), so we skip those to avoid a double render.
function withLiveTestimonials(html) {
  if (typeof html !== 'string' || html.indexOf('documents:runQuery') !== -1) return html;
  const KEY = FS_KEY;
  const script =
    '<script>(function(){' +
      'var m=location.pathname.match(/\\/p\\/([^\\/?#]+)/);if(!m)return;var slug=decodeURIComponent(m[1]);' +
      'if(document.querySelector("[data-r4u-live-testi]"))return;' +
      'var K="' + KEY + '";' +
      'fetch("https://firestore.googleapis.com/v1/projects/resume-ai-2eda1/databases/(default)/documents:runQuery?key="+K,{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify({structuredQuery:{from:[{collectionId:"testimonials"}],where:{fieldFilter:{field:{fieldPath:"slug"},op:"EQUAL",value:{stringValue:slug}}},limit:30}})})' +
      '.then(function(r){return r.ok?r.json():[];}).then(function(rows){' +
        'var qs=(rows||[]).map(function(x){return x.document&&x.document.fields;}).filter(function(f){return f&&f.status&&f.status.stringValue==="approved";});' +
        'if(!qs.length||document.querySelector("[data-r4u-live-testi]"))return;' +
        'function E(s){return String(s==null?"":s).replace(/&/g,"&amp;").replace(/</g,"&lt;").replace(/>/g,"&gt;");}' +
        'var cards=qs.map(function(f){var q=E(f.quote&&f.quote.stringValue),n=E(f.name&&f.name.stringValue),ro=E(f.role&&f.role.stringValue);' +
          'return "<figure style=\\"margin:0;padding:16px 18px;border:1px solid rgba(128,128,128,0.32);border-radius:12px;background:rgba(128,128,128,0.08);\\"><blockquote style=\\"margin:0;font-size:1rem;line-height:1.55;color:inherit;\\">\\u201c"+q+"\\u201d</blockquote>"+((n||ro)?"<figcaption style=\\"margin-top:10px;font-size:0.85rem;opacity:0.75;color:inherit;\\"><b>"+n+"</b>"+(ro?" \\u00b7 "+ro:"")+"</figcaption>":"")+"</figure>";' +
        '}).join("");' +
        'var sec=document.createElement("section");sec.setAttribute("data-r4u-live-testi","1");' +
        'sec.style.cssText="max-width:900px;margin:30px auto;padding:0 22px;box-sizing:border-box;font-family:inherit;";' +
        'sec.innerHTML="<h2 style=\\"font-size:1.3rem;margin:0 0 14px;font-weight:800;color:inherit;\\">Testimonials</h2><div style=\\"display:grid;gap:12px;\\">"+cards+"</div>";' +
        'var host=document.querySelector(".col")||document.querySelector("main")||document.querySelector(".app")||document.body;' +
        'var foot=host.querySelector&&host.querySelector(".foot");if(foot){host.insertBefore(sec,foot);}else{host.appendChild(sec);}' +
      '}).catch(function(){});' +
    '})();</script>';
  const i = html.lastIndexOf('</body>');
  return i === -1 ? html + script : html.slice(0, i) + script + html.slice(i);
}

function notFound() {
  return '<html><body style="font-family:sans-serif;text-align:center;padding:80px 20px;">'
    + '<h2>Portfolio not found</h2>'
    + '<p>This link may have expired. Generate a new one at '
    + '<a href="https://resume4u.help">resume4u.help</a>.</p>'
    + '</body></html>';
}

exports.withLiveTestimonials = withLiveTestimonials;
